package io.github.dotnetsupport.razor.lang.codegen

import io.github.dotnetsupport.razor.RazorDiagnosticSerializer
import io.github.dotnetsupport.razor.RazorDump
import io.github.dotnetsupport.razor.RazorMappingsSerializer
import io.github.dotnetsupport.razor.RazorMetrics
import io.github.dotnetsupport.razor.RazorTestUtil
import io.github.dotnetsupport.razor.lang.syntax.RazorLanguageVersion
import io.github.dotnetsupport.razor.lang.syntax.TagHelperCollection
import junit.framework.TestCase
import java.nio.file.Files
import java.nio.file.Path
import kotlin.io.path.name

/**
 * The code generation gate on the solutions of the corpus (RAZOR_PLAN.md, R3b): every `.razor` / `.cshtml` of MudBlazor, nopCommerce and
 * eShop generated by us against `razordump codegen` (the source generator's engine of the installed SDK), file by file — the generated C#,
 * `### mappings`, `### diagnostics` as razordump prints them. Both sides run without tag helper discovery (`--no-tag-helpers`: the port
 * has no Roslyn compilation to discover components in; `-Drazorpsi.codegenTagHelpers=true` lets razordump discover, for a look at what is
 * missing), the files read with LF, the generated document LF, the root namespace `ASP`, the paths relative.
 * Metrics: `testData/metrics/<name>-codegen.json` (`same` may only grow, `exceptions` only fall); differences: `build/razor-gate/<name>-codegen.txt`;
 * `-Drazorpsi.dump=<substring of a path>` writes both blocks in full. Skipped without the corpus or razordump.
 */
class RazorCodegenCorpusTest : TestCase() {

    fun testEshop() = gate("eshop", "razor/eshop/src")
    fun testMudblazor() = gate("mudblazor", "razor/mudblazor/src")
    fun testNopcommerce() = gate("nopcommerce", "razor/nopcommerce/src")

    // With tag helpers (RAZOR_PLAN.md, R5d): a project each, compiled as its build compiles it (tools/razor/README.md), the descriptors razordump
    // discovers in that compilation (`tag-helpers`, the same options) given to our engine — the lowering of components, `@bind`, event handlers,
    // MVC's tag helpers and view components against the compiler's.
    fun testEshopTagHelpers() = gateBuilt("eshop-th", "razor/eshop/src/WebApp", "razor/eshop/artifacts/obj/WebApp/debug/WebApp.GlobalUsings.g.cs", "razor/eshop/artifacts/bin/WebApp/debug", "WebApp.dll")
    fun testEshopComponentsTagHelpers() = gateBuilt(
        "eshop-components-th", "razor/eshop/src/WebAppComponents", "razor/eshop/artifacts/obj/WebAppComponents/debug/WebAppComponents.GlobalUsings.g.cs", null, null,
    )
    fun testMudblazorTagHelpers() = gateBuilt("mudblazor-th", "razor/mudblazor/src/MudBlazor", "razor/mudblazor/src/MudBlazor/obj/Debug/net10.0/MudBlazor.GlobalUsings.g.cs", null, null)
    fun testNopcommerceTagHelpers() = gateBuilt(
        "nopcommerce-th", "razor/nopcommerce/src/Presentation/Nop.Web", "razor/nopcommerce/src/Presentation/Nop.Web/obj/Debug/net10.0/Nop.Web.GlobalUsings.g.cs",
        "razor/nopcommerce/src/Presentation/Nop.Web/bin/Debug/net10.0", "Nop.Web.dll",
    )

    private fun gateBuilt(name: String, relative: String, globalUsings: String, bin: String?, own: String?) {
        val corpus = RazorTestUtil.corpusRoot()
        if (!Files.isDirectory(corpus.resolve(relative).resolve("obj")) && !Files.isDirectory(corpus.resolve(globalUsings).parent)) {
            return println("RazorCodegenCorpusTest: $relative is not built (tools/razor/README.md), $name skipped")
        }
        // a project without ImplicitUsings has no global usings
        val usings = corpus.resolve(globalUsings)
        val options = if (Files.isRegularFile(usings)) arrayListOf("--csharp", usings.toString()) else arrayListOf()
        if (bin != null) {
            val dlls = Files.list(corpus.resolve(bin)).use { s -> s.filter { it.fileName.toString().endsWith(".dll") && it.fileName.toString() != own }.map { it.toString() }.sorted().toList() }
            val list = RazorTestUtil.buildDir("razor-gate").resolve("$name.references.txt")
            Files.write(list, dlls)
            options += listOf("--references", "@$list")
        }
        gate(name, relative, options)
    }

    /** [tagHelperOptions]: discover tag helpers in the compilation of these razordump options (null: none, both sides `--no-tag-helpers`). */
    private fun gate(name: String, relative: String, tagHelperOptions: List<String>? = null) {
        val root = RazorTestUtil.corpusRoot().resolve(relative)
        if (!Files.isDirectory(root)) return println("RazorCodegenCorpusTest: $root is missing (tools/razor/fetch-corpus.sh), $name skipped")
        if (RazorDump.dll() == null) return println("RazorCodegenCorpusTest: razordump is not built (dotnet build tools/razor/razordump -c Release), $name skipped")
        val work = RazorTestUtil.buildDir("razor-gate")
        val dump = work.resolve("$name-codegen.oracle.txt")
        // The oracle is the installed SDK's compiler, whose latest language version is 10.0; ours follows the compiler's main (11.0), so
        // both sides are pinned to 10.0 (razordump takes the last --langversion).
        val options = (tagHelperOptions ?: listOf("--no-tag-helpers")) + listOf("--langversion", "10.0")
        println("  razordump codegen: " + RazorDump.codegen(root, dump, *options.toTypedArray()))
        val oracle = RazorDump.parseCodegen(Files.readString(dump))
        val tagHelpers = if (tagHelperOptions == null) TagHelperCollection.EMPTY else {
            val file = work.resolve("$name.taghelpers.json")
            println("  razordump tag-helpers: " + RazorDump.tagHelpers(root, file, *options.toTypedArray()))
            io.github.dotnetsupport.razor.lang.syntax.TagHelperDescriptorJson.read(Files.readString(file))
        }

        // razordump's file system (Codegen.ReadDirectory): every file under the root, Razor path `/rel`, physical and relative path `rel`,
        // the text with its line breaks LF, a BOM if the file had one
        val fileSystem = VirtualRazorProjectFileSystem()
        for (path in razorFiles(root)) {
            val bytes = Files.readAllBytes(root.resolve(path))
            val bom = bytes.size >= 3 && bytes[0] == 0xEF.toByte() && bytes[1] == 0xBB.toByte() && bytes[2] == 0xBF.toByte()
            val text = String(bytes, if (bom) 3 else 0, bytes.size - if (bom) 3 else 0, Charsets.UTF_8).replace("\r\n", "\n").replace('\r', '\n')
            fileSystem.add(RazorCodegenCases.TestProjectItem("/", "/$path", path, path, FileKinds.getFileKindFromPath(path), text, bom))
        }
        val engine = RazorCodegenCases.createGeneratorEngine(fileSystem, RazorLanguageVersion.VERSION_10_0, "ASP", "\n")

        var same = 0
        var exceptions = 0
        val diffs = ArrayList<String>()
        val started = System.nanoTime()
        for ((path, expectedRaw) in oracle) {
            val expected = normalize(expectedRaw)
            val actual = try {
                val item = fileSystem.getItem("/$path")
                val imports = RazorProjectEngine.getImportSourceDocuments(engine.getImports(item))
                val document = engine.process(item.getSource(), item.fileKind, imports, tagHelpers)
                normalize(codegenBlock(document))
            } catch (e: Throwable) {
                exceptions++
                diffs += "-- $path: ${e.javaClass.simpleName}: ${e.message}\n   at ${e.stackTrace.take(3).joinToString("\n   at ")}"
                continue
            }
            if (expected == actual) {
                same++
                continue
            }
            // -Drazorpsi.dump=<substring of a path>: both blocks in full, build/razor-gate/<file>.codegen.{oracle,ours}.txt
            val dumpName = System.getProperty("razorpsi.dump")
            if (!dumpName.isNullOrEmpty() && dumpName in path) {
                val base = work.resolve(path.substringAfterLast('/'))
                Files.writeString(Path.of("$base.codegen.oracle.txt"), expected)
                Files.writeString(Path.of("$base.codegen.ours.txt"), actual)
            }
            val a = expected.lines()
            val b = actual.lines()
            val i = a.indices.firstOrNull { it >= b.size || a[it] != b[it] } ?: a.size
            val section = a.subList(0, minOf(i, a.size)).lastOrNull { it == RazorDump.CODEGEN_MAPPINGS || it == RazorDump.CODEGEN_DIAGNOSTICS } ?: "code"
            diffs += "-- $path line ${i + 1} ($section)\n   oracle: ${a.getOrNull(i) ?: "<end>"}\n   ours:   ${b.getOrNull(i) ?: "<end>"}"
        }
        val report = StringBuilder("files ${oracle.size} same $same exceptions $exceptions, ${(System.nanoTime() - started) / 1_000_000} ms\n\n")
        diffs.take(500).forEach { report.append(it).append('\n') }
        val reportFile = work.resolve("$name-codegen.txt")
        Files.writeString(reportFile, report.toString())
        println("RazorCodegenCorpusTest $name: files ${oracle.size} same $same exceptions $exceptions (report: $reportFile)")
        RazorMetrics.check(
            Path.of(RazorTestUtil.testDataPath("metrics")).resolve("$name-codegen.json"),
            linkedMapOf("files" to oracle.size.toLong(), "same" to same.toLong(), "exceptions" to exceptions.toLong()),
            higherIsBetter = setOf("same"), lowerIsBetter = setOf("exceptions"),
        )
    }

    /** The block of a file as razordump's `AppendCodegen` writes it: the generated C#, `### mappings`, `### diagnostics`. */
    private fun codegenBlock(document: RazorCodeDocument): String {
        val csharpDocument = document.getCSharpDocument() ?: throw IllegalStateException("no C# document")
        val output = StringBuilder()
        appendSection(output, null, csharpDocument.generatedCode)
        appendSection(output, RazorDump.CODEGEN_MAPPINGS, RazorMappingsSerializer.serialize(csharpDocument, document.source))
        appendSection(output, RazorDump.CODEGEN_DIAGNOSTICS, RazorDiagnosticSerializer.serializeAll(csharpDocument.diagnostics))
        return output.toString()
    }

    /** `Codegen.AppendSection`: the header, the text with LF line breaks, a final one added when missing. */
    private fun appendSection(output: StringBuilder, header: String?, text: String) {
        if (header != null) output.append(header).append('\n')
        val lf = text.replace("\r\n", "\n")
        output.append(lf)
        if (lf.isNotEmpty() && !lf.endsWith('\n')) output.append('\n')
    }

    /** As [RazorDump.parseCodegen] reads a block: line by line (a lone CR ends a line too), the final line breaks dropped. */
    private fun normalize(text: String): String = text.lineSequence().joinToString("\n").trimEnd('\n')

    /** razordump's `EnumerateFiles`: `.razor` / `.cshtml` under [root] (`bin`, `obj`, `.git`, `node_modules` skipped), ordinal order. */
    private fun razorFiles(root: Path): List<String> = Files.walk(root).use { s ->
        s.filter { Files.isRegularFile(it) && (it.name.endsWith(".razor", ignoreCase = true) || it.name.endsWith(".cshtml", ignoreCase = true)) }
            .map { root.relativize(it).toString().replace('\\', '/') }
            .filter { r -> r.split('/').none { it == "bin" || it == "obj" || it == ".git" || it == "node_modules" } }
            .toList()
    }.sorted()
}
