"""Generates the syntax kinds and the node classes of razor-psi-core from the Razor compiler's SyntaxKind.cs and Syntax.xml
(RAZOR_PLAN.md, R2; as roslyndump gen-kinds / gen-psi do for csharp-psi). The compiler is the corpus checkout (tools/razor/README.md):

    uv run --no-project python tools/razor/gen_syntax.py

Writes razor-psi-core/src/main/kotlin/io/github/dotnetsupport/razor/lang/syntax/RazorSyntaxKind.kt and RazorSyntaxNodes.kt. The node
classes mirror Syntax.xml: one Kotlin class per <Node>, abstract classes for <AbstractNode>, fields of node or token types as slots
(SyntaxList fields as RazorList), the other fields (bool, chunk generator, edit handler, directive descriptor, tag helper infos) as
plain properties. Do not edit the generated files: rerun this script.
"""
import io
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
COMPILER = os.path.join(ROOT, ".corpus", "razor", "razor-compiler", "src", "Razor", "src", "Compiler", "Microsoft.CodeAnalysis.Razor.Compiler", "src", "Language")
OUT = os.path.join(ROOT, "razor-psi-core", "src", "main", "kotlin", "io", "github", "dotnetsupport", "razor", "lang", "syntax")
HEADER = "// Generated by tools/razor/gen_syntax.py from the Razor compiler's {source} (the corpus checkout, tools/razor/README.md).\n// Do not edit: rerun the script. Razor: Copyright (c) .NET Foundation and Contributors, MIT License (NOTICE.md).\n"


def kinds():
    text = io.open(os.path.join(COMPILER, "Syntax", "SyntaxKind.cs"), encoding="utf-8-sig").read()
    body = text[text.index("{", text.index("enum SyntaxKind")) + 1:]
    body = body[:body.index("}")]
    names = []
    tokens_from = None
    for line in body.split("\n"):
        line = line.split("//")[0].strip()
        if line == "#region Tokens":
            tokens_from = len(names)
        m = re.fullmatch(r"(\w+),?", line)
        if m:
            names.append(m.group(1))
    out = [HEADER.format(source="Syntax/SyntaxKind.cs"), "package io.github.dotnetsupport.razor.lang.syntax", "",
           "/** The compiler's `SyntaxKind`: the node kinds, then (from [Marker]) the token kinds. */", "enum class RazorSyntaxKind {"]
    for i, n in enumerate(names):
        out.append(f"    {n},")
    out.append("    ;")
    out.append("")
    out.append(f"    val isTokenKind: Boolean get() = ordinal >= Marker.ordinal && this != FirstAvailableTokenKind")
    out.append("}")
    io.open(os.path.join(OUT, "RazorSyntaxKind.kt"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    return names


KOTLIN_TYPES = {
    "bool": "Boolean",
    "ISpanChunkGenerator": "ChunkGenerator?",
    "SpanEditHandler": "SpanEditHandler?",
    "DirectiveDescriptor": "DirectiveDescriptor?",
    "TagHelperInfo": "TagHelperInfo?",
    "TagHelperAttributeInfo": "TagHelperAttributeInfo?",
}


def is_node_type(t):
    return t == "SyntaxToken" or t.startswith("SyntaxList<") or t.endswith("Syntax") or t.endswith("SyntaxNode")


def kotlin_type(t, optional):
    if t == "SyntaxToken":
        return "RazorToken" + ("?" if optional else "")
    if t.startswith("SyntaxList<"):
        return "RazorList"
    if t in KOTLIN_TYPES:
        return KOTLIN_TYPES[t]
    return t + ("?" if optional else "")


def lower(name):
    if name.startswith("CSharp"):
        return "csharp" + name[len("CSharp"):]
    return name[0].lower() + name[1:]


def nodes():
    tree = ET.parse(os.path.join(COMPILER, "Syntax", "Syntax.xml"))
    root = tree.getroot()
    out = [HEADER.format(source="Syntax/Syntax.xml"), "@file:Suppress(\"unused\")", "", "package io.github.dotnetsupport.razor.lang.syntax", ""]
    abstract_fields = {}  # name -> [(fieldName, type, optional)]
    for el in root:
        if el.tag == "PredefinedNode":
            continue
        name = el.get("Name")
        base = el.get("Base")
        fields = []
        for f in el.findall("Field"):
            fields.append((f.get("Name"), f.get("Type"), f.get("Optional") == "true", f.get("Override") == "true"))
        if el.tag == "AbstractNode":
            abstract_fields[name] = fields
            out.append(f"abstract class {name}(kind: RazorSyntaxKind) : {base}(kind) {{")
            for fname, ftype, optional, _ in fields:
                out.append(f"    abstract val {lower(fname)}: {kotlin_type(ftype, optional)}")
            out.append("}")
            out.append("")
        elif el.tag == "Node":
            kind = el.find("Kind").get("Name")
            inherited = {}
            b = base
            while b in abstract_fields:
                for fname, ftype, optional, _ in abstract_fields[b]:
                    inherited[fname] = (ftype, optional)
                b = None
            params = []
            slots = []
            props = []
            for fname, ftype, optional, override in fields:
                kt = kotlin_type(ftype, optional)
                mod = "override " if (override or fname in inherited) else ""
                if is_node_type(ftype):
                    params.append(f"{mod}val {lower(fname)}: {kt}")
                    slots.append(lower(fname))
                else:
                    default = " = false" if ftype == "bool" else " = null"
                    params.append(f"{mod}val {lower(fname)}: {kt}{default}")
            # an abstract field of the base the node spells differently (BaseMarkupElementSyntax.StartTag is MarkupElementSyntax.MarkupStartTag,
            # MarkupTagHelperElementSyntax.TagHelperStartTag): the compiler implements it by hand, here it is generated
            own = {fname for fname, _, _, _ in fields}
            bridged = []
            for fname, (ftype, optional) in inherited.items():
                if fname not in own:
                    match = next((f for f, _, _, _ in fields if f.endswith(fname)), None)
                    if match is None:
                        raise SystemExit(f"{name}: no field for the abstract {fname} of {base}")
                    bridged.append(f"    override val {lower(fname)}: {kotlin_type(ftype, optional)} get() = {lower(match)}")
            out.append(f"/** `{kind}`. */")
            out.append(f"class {name}(")
            for p in params:
                out.append(f"    {p},")
            out.append(f") : {base}(RazorSyntaxKind.{kind}) {{")
            out.extend(bridged)
            out.append(f"    override val slotCount: Int get() = {len(slots)}")
            out.append("    override fun slot(index: Int): RazorNode? = when (index) {")
            for i, s in enumerate(slots):
                out.append(f"        {i} -> {s}")
            out.append("        else -> throw IndexOutOfBoundsException(\"slot $index of $kind\")")
            out.append("    }")
            out.append("}")
            out.append("")
    io.open(os.path.join(OUT, "RazorSyntaxNodes.kt"), "w", encoding="utf-8", newline="\n").write("\n".join(out))


RED_OUT = os.path.join(OUT, "red")
GREEN = "io.github.dotnetsupport.razor.lang.syntax."


def red_type(t, optional):
    """The red-side type of a field: tokens are RedToken, lists are List<RedNode> (of tokens: List<RedToken>), nodes keep their names."""
    if t == "SyntaxToken":
        return "RedToken" + ("?" if optional else "")
    if t == "SyntaxList<SyntaxToken>":
        return "List<RedToken>"
    if t.startswith("SyntaxList<"):
        return "List<RedNode>"
    if t == "RazorSyntaxNode" or t == "SyntaxNode":
        return "RedNode" + ("?" if optional else "")
    if t.endswith("Syntax") or t.endswith("SyntaxNode"):
        return t + ("?" if optional else "")
    return KOTLIN_TYPES.get(t, t)


def red_nodes():
    """The red tree (RAZOR_PLAN.md, R3b): a node per green node with its parent and position, typed slot accessors, the plain properties
    delegated to the green node, `accept` for the red visitor; the visitor and the factory from the same list."""
    tree = ET.parse(os.path.join(COMPILER, "Syntax", "Syntax.xml"))
    root = tree.getroot()
    out = [HEADER.format(source="Syntax/Syntax.xml"), "@file:Suppress(\"unused\", \"UNCHECKED_CAST\")", "",
           "package io.github.dotnetsupport.razor.lang.syntax.red", "",
           "import io.github.dotnetsupport.razor.lang.syntax.ChunkGenerator", "import io.github.dotnetsupport.razor.lang.syntax.DirectiveDescriptor",
           "import io.github.dotnetsupport.razor.lang.syntax.RazorNode", "import io.github.dotnetsupport.razor.lang.syntax.RazorToken",
           "import io.github.dotnetsupport.razor.lang.syntax.SpanEditHandler", "import io.github.dotnetsupport.razor.lang.syntax.TagHelperAttributeInfo",
           "import io.github.dotnetsupport.razor.lang.syntax.TagHelperInfo", ""]
    abstract_fields = {}
    concrete = []  # (name, kind)
    for el in root:
        if el.tag == "PredefinedNode":
            continue
        name = el.get("Name")
        base = el.get("Base")
        base_red = "RedNode" if base in ("SyntaxNode", "RazorSyntaxNode") else base
        fields = [(f.get("Name"), f.get("Type"), f.get("Optional") == "true", f.get("Override") == "true") for f in el.findall("Field")]
        if el.tag == "AbstractNode":
            abstract_fields[name] = fields
            out.append(f"abstract class {name}(green: RazorNode, parent: RedNode?, position: Int) : {base_red}(green, parent, position) {{")
            for fname, ftype, optional, _ in fields:
                out.append(f"    abstract val {lower(fname)}: {red_type(ftype, optional)}")
            out.append("}")
            out.append("")
        elif el.tag == "Node":
            kind = el.find("Kind").get("Name")
            concrete.append((name, kind))
            inherited = {}
            b = base
            while b in abstract_fields:
                for fname, ftype, optional, _ in abstract_fields[b]:
                    inherited[fname] = (ftype, optional)
                b = None
            own = {fname for fname, _, _, _ in fields}
            out.append(f"/** `{kind}`. */")
            out.append(f"class {name}(green: {GREEN}{name}, parent: RedNode?, position: Int) : {base_red}(green, parent, position) {{")
            out.append(f"    val greenNode: {GREEN}{name} get() = green as {GREEN}{name}")
            slot = 0
            for fname, ftype, optional, override in fields:
                rt = red_type(ftype, optional)
                mod = "override " if (override or fname in inherited) else ""
                if is_node_type(ftype):
                    if ftype == "SyntaxToken":
                        expr = f"slotToken({slot})" + ("" if optional else "!!")
                    elif ftype == "SyntaxList<SyntaxToken>":
                        expr = f"slotList({slot}) as List<RedToken>"
                    elif ftype.startswith("SyntaxList<"):
                        expr = f"slotList({slot})"
                    else:
                        expr = f"slotNode({slot}) as {rt}" if optional else f"slotNode({slot}) as {rt}"
                    out.append(f"    {mod}val {lower(fname)}: {rt} get() = {expr}")
                    slot += 1
                else:
                    out.append(f"    {mod}val {lower(fname)}: {rt} get() = greenNode.{lower(fname)}")
            for fname, (ftype, optional) in inherited.items():
                if fname not in own:
                    match = next((f for f, _, _, _ in fields if f.endswith(fname)), None)
                    out.append(f"    override val {lower(fname)}: {red_type(ftype, optional)} get() = {lower(match)}")
            short = name[:-len("Syntax")] if name.endswith("Syntax") else name
            out.append(f"    override fun accept(visitor: RedSyntaxVisitor) = visitor.visit{short}(this)")
            out.append("}")
            out.append("")
    # the visitor: one method per concrete node, the tokens, the default
    out.append("/** `SyntaxVisitor`: a method per node kind, each falling back to [defaultVisit]. */")
    out.append("open class RedSyntaxVisitor {")
    out.append("    open fun visit(node: RedNode?) {")
    out.append("        node?.accept(this)")
    out.append("    }")
    out.append("    open fun defaultVisit(node: RedNode) {}")
    out.append("    open fun visitToken(token: RedToken) = defaultVisit(token)")
    for name, _ in concrete:
        short = name[:-len("Syntax")] if name.endswith("Syntax") else name
        out.append(f"    open fun visit{short}(node: {name}) = defaultVisit(node)")
    out.append("}")
    out.append("")
    out.append("/** `SyntaxWalker`: visits the children (nodes and tokens) by default. */")
    out.append("open class RedSyntaxWalker : RedSyntaxVisitor() {")
    out.append("    override fun defaultVisit(node: RedNode) {")
    out.append("        for (child in node.childNodesAndTokens()) visit(child)")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("/** The red node of a green one. */")
    out.append("object RedNodes {")
    out.append("    fun create(green: RazorNode, parent: RedNode?, position: Int): RedNode = when (green) {")
    out.append("        is RazorToken -> RedToken(green, parent, position)")
    for name, _ in concrete:
        out.append(f"        is {GREEN}{name} -> {name}(green, parent, position)")
    out.append("        else -> throw IllegalArgumentException(\"no red node for ${green.kind}\")")
    out.append("    }")
    out.append("}")
    os.makedirs(RED_OUT, exist_ok=True)
    io.open(os.path.join(RED_OUT, "RazorRedNodes.kt"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    names = kinds()
    nodes()
    red_nodes()
    print(f"kinds: {len(names)}; nodes written to {OUT}, red nodes to {RED_OUT}")
